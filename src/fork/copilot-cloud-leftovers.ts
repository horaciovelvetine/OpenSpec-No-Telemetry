import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import chalk from 'chalk';

/** SHA-256 of LF-normalized upstream-managed Copilot cloud-agent templates (v1.14.1). */
export const MANAGED_COPILOT_CONTENT_SHA256 = new Set([
	'69ce5d8c4f4c02581a91a8f3bdb52590d621b2b0c6283d09f9ac03ee50754256',
	'89b7c5e60376c9af32d6769f303e4cd8d31bbc6e85ad7f1c6da076395b9cbeae',
	'ebf56e544c6939eb6cf48e8878c599ffb93dd181e8c93c7488b5993eef4655ff',
	'db9af4bcda81440af9d8c600f98f60cada6b8b3f36d831c03d0acf0382edfb27',
	'9b4d148e020fc89de8d941539ce2e1555bc5f604fcc9199654635316bc57256a',
	'5180fbcf10c30ba63b99dc52110686c9408363f367a4880dd0e40b321707b90d',
	'30c00a5e4f7f22006b24636a53ae1c37a1a7c8832c23424a834b21ae2ca3c844',
]);

const SETUP_REL = path.join('.github', 'workflows', 'copilot-setup-steps.yml');
const AGENT_REL = path.join('.github', 'agents', 'openspec.agent.md');
const AGENTS_DIR = path.join('.github', 'agents');

const MANAGED_MARKER =
	'Generated by OpenSpec for GitHub Copilot coding agent support.';
const UPSTREAM_PACKAGE_MARKER = '@fission-ai/openspec';

function hashContent(content: string): string {
	return crypto
		.createHash('sha256')
		.update(content.replace(/\r\n/g, '\n'))
		.digest('hex');
}

async function tryRemoveEmptyAgentsDir(projectPath: string): Promise<void> {
	const agentsDir = path.join(projectPath, AGENTS_DIR);
	try {
		const entries = await fs.readdir(agentsDir);
		if (entries.length === 0) {
			await fs.rmdir(agentsDir);
		}
	} catch {
		// Missing or not empty — leave it.
	}
}

async function processFile(
	projectPath: string,
	relPath: string,
): Promise<void> {
	const fullPath = path.join(projectPath, relPath);
	let stat;
	try {
		stat = await fs.stat(fullPath);
	} catch {
		return;
	}
	if (!stat.isFile()) {
		return;
	}

	const content = await fs.readFile(fullPath, 'utf-8');
	if (MANAGED_COPILOT_CONTENT_SHA256.has(hashContent(content))) {
		await fs.unlink(fullPath);
		if (relPath === AGENT_REL) {
			await tryRemoveEmptyAgentsDir(projectPath);
		}
		console.log(
			chalk.dim(`Removed upstream Copilot cloud-agent file: ${relPath}`),
		);
		return;
	}

	if (
		content.includes(MANAGED_MARKER) ||
		content.includes(UPSTREAM_PACKAGE_MARKER)
	) {
		console.log(
			chalk.yellow(
				`Warning: ${relPath} looks like an upstream OpenSpec Copilot cloud-agent file. ` +
					'It can still install upstream OpenSpec. Delete it or adapt it for your vendored build.',
			),
		);
	}
}

/**
 * Removes unmodified upstream Copilot cloud-agent files and warns on customized
 * copies. Never throws; failures are reported as warnings.
 */
export async function removeCopilotCloudLeftovers(
	projectPath: string,
): Promise<void> {
	try {
		for (const relPath of [SETUP_REL, AGENT_REL]) {
			await processFile(projectPath, relPath);
		}
	} catch (error) {
		const message = error instanceof Error ? error.message : String(error);
		console.warn(
			`Warning: failed to check Copilot cloud-agent leftovers: ${message}`,
		);
	}
}
